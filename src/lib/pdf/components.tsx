interface TableProps {
  headers: string[];
  rows: string[][];
  widths?: number[];
}

export const Table: React.FC<TableProps> = ({ headers, rows, widths }) => {
  const cellWidths = widths || Array(headers.length).fill(100 / headers.length);

  return (
    <View style={styles.table}>
      <View style={styles.tableRow}>
        {headers.map((header, index) => (
          <View
            key={index}
            style={[styles.tableCellHeader, { width: `${cellWidths[index]}%` }]}
          >
            <Text>{header}</Text>
          </View>
        ))}
      </View>
      {rows.map((row, rowIndex) => (
        <View key={rowIndex} style={styles.tableRow}>
          {row.map((cell, cellIndex) => (
            <View
              key={cellIndex}
              style={[styles.tableCell, { width: `${cellWidths[cellIndex]}%` }]}
            >
              <Text>{cell}</Text>
            </View>
          ))}
        </View>
      ))}
    </View>
  );
};

