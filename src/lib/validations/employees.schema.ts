import { z } from "zod";
import { EmploymentStatusEnum, PaymentMethodEnum } from "./common.schema";

// ============================================================================
// EMPLOYEES
// ============================================================================

const EmployeeBaseSchema = z.object({
  id: z.string().uuid().optional(),
  full_name: z
    .string()
    .min(1, "Full name is required")
    .max(255, "Full name must be at most 255 characters")
    .refine((val) => val.trim().length > 0, "Full name is required"),
  email: z
    .string()
    .min(1, "Email is required")
    .email("Invalid email address")
    .max(255, "Email must be at most 255 characters")
    .refine((val) => val.trim().length > 0, "Email is required"),
  phone: z
    .string()
    .min(1, "Phone is required")
    .max(50, "Phone must be at most 50 characters")
    .refine((val) => val.trim().length > 0, "Phone is required"),
  address: z
    .string()
    .min(1, "Address is required")
    .refine((val) => val.trim().length > 0, "Address is required"),
  position: z
    .string()
    .min(1, "Position is required")
    .max(150, "Position must be at most 150 characters")
    .refine((val) => val.trim().length > 0, "Position is required"),
  salary: z
    .number()
    .nonnegative("Salary must be non-negative")
    .refine((val) => val >= 0, "Salary must be greater than or equal to 0")
    .default(0),
  employment_date: z
    .string()
    .refine((val) => !isNaN(Date.parse(val)), "Invalid employment date"),
  status: EmploymentStatusEnum.default("active"),
  notes: z.string().nullable().optional(),
  created_at: z.string().datetime().optional(),
  updated_at: z.string().datetime().optional(),
});

export const EmployeeSchema = EmployeeBaseSchema;

export type EmployeeInput = z.infer<typeof EmployeeSchema>;

// Schema for creating a new employee (id is generated by database)
export const EmployeeCreateSchema = EmployeeBaseSchema.omit({ id: true });

export type EmployeeCreate = z.infer<typeof EmployeeCreateSchema>;

export const EmployeeUpdateSchema = EmployeeBaseSchema.partial().extend({
  id: z.string().uuid(),
});

export type EmployeeUpdate = z.infer<typeof EmployeeUpdateSchema>;

// ============================================================================
// PAYROLL PERIODS
// ============================================================================

const PayrollPeriodBaseSchema = z.object({
  id: z.string().uuid().optional(),
  employee_id: z.string().uuid("Invalid employee ID"),
  period_start: z
    .string()
    .refine((val) => !isNaN(Date.parse(val)), "Invalid start date"),
  period_end: z
    .string()
    .refine((val) => !isNaN(Date.parse(val)), "Invalid end date"),
  salary_amount: z
    .number()
    .nonnegative("Salary amount must be non-negative")
    .refine(
      (val) => val >= 0,
      "Salary amount must be greater than or equal to 0",
    ),
  created_at: z.string().datetime().optional(),
});

export const PayrollPeriodSchema = PayrollPeriodBaseSchema.refine(
  (data) => new Date(data.period_end) >= new Date(data.period_start),
  {
    message: "Period end date must be after or equal to period start date",
    path: ["period_end"],
  },
);

export type PayrollPeriodInput = z.infer<typeof PayrollPeriodSchema>;

export const PayrollPeriodUpdateSchema =
  PayrollPeriodBaseSchema.partial().extend({
    id: z.string().uuid(),
  });

export type PayrollPeriodUpdate = z.infer<typeof PayrollPeriodUpdateSchema>;

// ============================================================================
// SALARY PAYMENTS
// ============================================================================

export const SalaryPaymentSchema = z.object({
  id: z.string().uuid().optional(),
  payroll_period_id: z.string().uuid("Invalid payroll period ID"),
  amount: z.number().positive("Payment amount must be greater than zero"),
  payment_date: z
    .string()
    .refine((val) => !isNaN(Date.parse(val)), "Invalid payment date")
    .default(new Date().toISOString().split("T")[0]),
  method: PaymentMethodEnum,
  reference_number: z
    .string()
    .max(255, "Reference number must be at most 255 characters")
    .nullable()
    .optional(),
  notes: z.string().nullable().optional(),
  recorded_by: z.string().uuid().nullable().optional(),
  created_at: z.string().datetime().optional(),
});

export type SalaryPaymentInput = z.infer<typeof SalaryPaymentSchema>;

// ============================================================================
// RPC FUNCTION SCHEMAS
// ============================================================================

export const RecordSalaryPaymentSchema = z.object({
  p_payroll_period_id: z.string().uuid("Invalid payroll period ID"),
  p_amount: z.number().positive("Payment amount must be greater than zero"),
  p_payment_date: z
    .string()
    .refine((val) => !isNaN(Date.parse(val)), "Invalid payment date")
    .nullable()
    .optional(),
  p_method: PaymentMethodEnum,
  p_reference_number: z.string().nullable().optional(),
  p_notes: z.string().nullable().optional(),
});

export type RecordSalaryPaymentInput = z.infer<
  typeof RecordSalaryPaymentSchema
>;
