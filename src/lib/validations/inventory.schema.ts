import { z } from "zod";
import { InventoryActivityTypeEnum } from "./common.schema";

// ============================================================================
// WAREHOUSES
// ============================================================================

export const WarehouseSchema = z.object({
  id: z.string().uuid().optional(),
  name: z
    .string()
    .min(1, "Warehouse name is required")
    .max(255, "Warehouse name must be at most 255 characters"),
  address: z.string().nullable().optional(),
  description: z.string().nullable().optional(),
  created_at: z.string().datetime().optional(),
});

export type WarehouseInput = z.infer<typeof WarehouseSchema>;

// Schema for creating a new warehouse (id is generated by database)
export const WarehouseCreateSchema = WarehouseSchema.omit({ id: true });

export type WarehouseCreate = z.infer<typeof WarehouseCreateSchema>;

export const WarehouseUpdateSchema = WarehouseSchema.partial().extend({
  id: z.string().uuid(),
});

export type WarehouseUpdate = z.infer<typeof WarehouseUpdateSchema>;

// ============================================================================
// INVENTORY ITEMS
// ============================================================================

export const InventoryItemSchema = z.object({
  id: z.string().uuid().optional(),
  name: z
    .string()
    .min(1, "Item name is required")
    .max(255, "Item name must be at most 255 characters"),
  sku: z
    .string()
    .min(1, "SKU is required")
    .max(100, "SKU must be at most 100 characters"),
  description: z.string().nullable().optional(),
  unit: z
    .string()
    .min(1, "Unit is required")
    .max(50, "Unit must be at most 50 characters"),
  created_at: z.string().datetime().optional(),
});

export type InventoryItemInput = z.infer<typeof InventoryItemSchema>;

// Schema for creating a new inventory item (id is generated by database)
export const InventoryItemCreateSchema = InventoryItemSchema.omit({ id: true });

export type InventoryItemCreate = z.infer<typeof InventoryItemCreateSchema>;

export const InventoryItemUpdateSchema = InventoryItemSchema.partial().extend({
  id: z.string().uuid(),
});

export type InventoryItemUpdate = z.infer<typeof InventoryItemUpdateSchema>;

// ============================================================================
// WAREHOUSE STOCK
// ============================================================================

const WarehouseStockBaseSchema = z.object({
  id: z.string().uuid().optional(),
  item_id: z.string().uuid("Invalid item ID"),
  warehouse_id: z.string().uuid("Invalid warehouse ID"),
  total_quantity: z
    .number()
    .nonnegative("Total quantity must be non-negative")
    .refine(
      (val) => val >= 0,
      "Total quantity must be greater than or equal to 0",
    )
    .default(0),
  reserved_quantity: z
    .number()
    .nonnegative("Reserved quantity must be non-negative")
    .refine(
      (val) => val >= 0,
      "Reserved quantity must be greater than or equal to 0",
    )
    .default(0),
  used_quantity: z
    .number()
    .nonnegative("Used quantity must be non-negative")
    .refine(
      (val) => val >= 0,
      "Used quantity must be greater than or equal to 0",
    )
    .default(0),
  available_quantity: z.number().nullable().optional(),
  updated_at: z.string().datetime().optional(),
});

export const WarehouseStockSchema = WarehouseStockBaseSchema.refine(
  (data) => data.total_quantity >= data.reserved_quantity + data.used_quantity,
  {
    message:
      "Total quantity must be at least the sum of reserved and used quantities",
    path: ["total_quantity"],
  },
);

export type WarehouseStockInput = z.infer<typeof WarehouseStockSchema>;

// ============================================================================
// WAREHOUSE TRANSFERS
// ============================================================================

const WarehouseTransferBaseSchema = z.object({
  id: z.string().uuid().optional(),
  item_id: z.string().uuid("Invalid item ID"),
  source_warehouse_id: z.string().uuid("Invalid source warehouse ID"),
  destination_warehouse_id: z.string().uuid("Invalid destination warehouse ID"),
  quantity: z.number().positive("Transfer quantity must be greater than zero"),
  transfer_date: z.string().datetime().optional(),
  notes: z.string().nullable().optional(),
  performed_by: z.string().uuid().nullable().optional(),
  created_at: z.string().datetime().optional(),
});

export const WarehouseTransferSchema = WarehouseTransferBaseSchema.refine(
  (data) => data.source_warehouse_id !== data.destination_warehouse_id,
  {
    message: "Source and destination warehouses must be different",
    path: ["destination_warehouse_id"],
  },
);

export type WarehouseTransferInput = z.infer<typeof WarehouseTransferSchema>;

// ============================================================================
// INVENTORY ACTIVITY LOGS
