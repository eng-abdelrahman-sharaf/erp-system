import { z } from "zod";
import { OrderStatusEnum } from "./common.schema";

// ============================================================================
// ORDERS
// ============================================================================

export const OrderSchema = z.object({
  id: z.string().uuid().optional(),
  order_number: z
    .string()
    .min(1, "Order number is required")
    .max(100, "Order number must be at most 100 characters"),
  title: z
    .string()
    .min(1, "Title is required")
    .max(255, "Title must be at most 255 characters"),
  description: z.string().nullable().optional(),
  client_name: z
    .string()
    .min(1, "Client name is required")
    .max(255, "Client name must be at most 255 characters"),
  client_phone: z
    .string()
    .min(1, "Client phone is required")
    .max(50, "Client phone must be at most 50 characters")
    .refine((val) => val.trim().length > 0, "Client phone is required"),
  client_address: z
    .string()
    .min(1, "Client address is required")
    .refine((val) => val.trim().length > 0, "Client address is required"),
  employee_id: z.string().uuid("Invalid employee ID").nullable().optional(),
  status: OrderStatusEnum.default("pending"),
  order_date: z
    .string()
    .refine((val) => !isNaN(Date.parse(val)), "Invalid order date")
    .default(new Date().toISOString().split("T")[0]),
  notes: z.string().nullable().optional(),
  created_by: z.string().uuid("Invalid user ID"),
  created_at: z.string().datetime().optional(),
  updated_at: z.string().datetime().optional(),
});

export type OrderInput = z.infer<typeof OrderSchema>;

// Schema for creating a new order (id and created_by are generated by database/auth)
export const OrderCreateSchema = OrderSchema.omit({
  id: true,
  created_by: true,
});

export type OrderCreate = z.infer<typeof OrderCreateSchema>;

export const OrderUpdateSchema = OrderSchema.partial().extend({
  id: z.string().uuid(),
});

export type OrderUpdate = z.infer<typeof OrderUpdateSchema>;

// ============================================================================
// ORDER INVENTORY
// ============================================================================

export const OrderInventorySchema = z.object({
  id: z.string().uuid().optional(),
  order_id: z.string().uuid("Invalid order ID"),
  item_id: z.string().uuid("Invalid item ID"),
  warehouse_id: z.string().uuid("Invalid warehouse ID"),
  quantity: z.number().positive("Quantity must be greater than zero"),
  unit: z
    .string()
    .min(1, "Unit is required")
    .max(50, "Unit must be at most 50 characters"),
  created_at: z.string().datetime().optional(),
});

export type OrderInventoryInput = z.infer<typeof OrderInventorySchema>;

// ============================================================================
// ORDER NOTES
// ============================================================================

export const OrderNoteSchema = z.object({
  id: z.string().uuid().optional(),
  order_id: z.string().uuid("Invalid order ID"),
  content: z
    .string()
    .min(1, "Content is required")
    .refine(
      (val) => val.trim().length > 0,
      "Content cannot be empty or whitespace only",
    ),
  created_by: z.string().uuid().nullable().optional(),
  created_at: z.string().datetime().optional(),
});

export type OrderNoteInput = z.infer<typeof OrderNoteSchema>;

// ============================================================================
// ORDER ACTIVITY LOGS
// ============================================================================

export const OrderActivityLogSchema = z.object({
  id: z.string().uuid().optional(),
  order_id: z.string().uuid("Invalid order ID"),
  activity_type: z.string().min(1, "Activity type is required"),
  description: z.string().min(1, "Description is required"),
  performed_by: z.string().uuid().nullable().optional(),
  created_at: z.string().datetime().optional(),
});

export type OrderActivityLogInput = z.infer<typeof OrderActivityLogSchema>;

// ============================================================================
// RPC FUNCTION SCHEMAS
// ============================================================================

export const ReserveOrderInventorySchema = z.object({
  p_order_id: z.string().uuid("Invalid order ID"),
  p_item_id: z.string().uuid("Invalid item ID"),
  p_warehouse_id: z.string().uuid("Invalid warehouse ID"),
  p_quantity: z.number().positive("Quantity must be greater than zero"),
});

export type ReserveOrderInventoryInput = z.infer<
  typeof ReserveOrderInventorySchema
>;

export const ChangeOrderStatusSchema = z.object({
  p_order_id: z.string().uuid("Invalid order ID"),
  p_new_status: z.enum(["paid", "cancelled"]),
});

export type ChangeOrderStatusInput = z.infer<typeof ChangeOrderStatusSchema>;
