import { z } from "zod";
import { ModuleNameEnum } from "./common.schema";

// ============================================================================
// ROLES
// ============================================================================

export const RoleSchema = z.object({
  id: z.string().uuid().optional(),
  name: z
    .string()
    .min(1, "Role name is required")
    .max(100, "Role name must be at most 100 characters"),
  description: z.string().nullable().optional(),
  created_at: z.string().datetime().optional(),
});

export type RoleInput = z.infer<typeof RoleSchema>;

// Schema for creating a new role (id is generated by database)
export const RoleCreateSchema = RoleSchema.omit({ id: true });

export type RoleCreate = z.infer<typeof RoleCreateSchema>;

export const RoleUpdateSchema = RoleSchema.partial().extend({
  id: z.string().uuid(),
});

export type RoleUpdate = z.infer<typeof RoleUpdateSchema>;

// ============================================================================
// ROLE PERMISSIONS
// ============================================================================

const RolePermissionBaseSchema = z.object({
  id: z.string().uuid().optional(),
  role_id: z.string().uuid("Invalid role ID"),
  module: ModuleNameEnum,
  can_read: z.boolean().default(false),
  can_write: z.boolean().default(false),
  created_at: z.string().datetime().optional(),
});

export const RolePermissionSchema = RolePermissionBaseSchema.refine(
  (data) => !data.can_write || data.can_read,
  {
    message: "Write permission requires read permission",
    path: ["can_write"],
  },
);

export type RolePermissionInput = z.infer<typeof RolePermissionSchema>;

export const RolePermissionUpdateSchema =
  RolePermissionBaseSchema.partial().extend({
    id: z.string().uuid(),
  });

export type RolePermissionUpdate = z.infer<typeof RolePermissionUpdateSchema>;
