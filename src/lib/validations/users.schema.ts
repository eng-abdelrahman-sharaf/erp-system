import { z } from "zod";
import { AccountStatusEnum } from "./common.schema";

// ============================================================================
// PROFILES (USERS)
// ============================================================================

export const ProfileSchema = z.object({
  id: z.string().uuid(),
  full_name: z
    .string()
    .min(1, "Full name is required")
    .max(255, "Full name must be at most 255 characters"),
  email: z
    .string()
    .min(1, "Email is required")
    .email("Invalid email address")
    .max(255, "Email must be at most 255 characters"),
  role_id: z.string().uuid("Invalid role ID"),
  status: AccountStatusEnum.default("active"),
  created_at: z.string().datetime().optional(),
});

export type ProfileInput = z.infer<typeof ProfileSchema>;

// Schema for creating a new user (id is generated by auth)
export const ProfileCreateSchema = ProfileSchema.omit({ id: true });

export type ProfileCreate = z.infer<typeof ProfileCreateSchema>;

export const ProfileUpdateSchema = ProfileSchema.partial().extend({
  id: z.string().uuid(),
});

export type ProfileUpdate = z.infer<typeof ProfileUpdateSchema>;
